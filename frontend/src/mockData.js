export function getTeacherPhoto(teacher) {
  if (teacher?.photo_url && teacher.photo_url.length > 20) return teacher.photo_url;
  const desig = (teacher?.designation || '').toLowerCase();
  const name = (teacher?.name_bn || teacher?.name_en || '').toLowerCase();
  const role = (teacher?.public_contact_role || teacher?.role || '').toLowerCase();
  const empId = (teacher?.employee_id || teacher?.id || '').toLowerCase();
  
  if (role === 'head_teacher' || (desig.includes('প্রধান শিক্ষক') && !desig.includes('সহকারী')) || name.includes('শফিকুল')) {
    return PHOTO_HEAD_TEACHER;
  }
  if (role === 'assistant_head_teacher' || desig.includes('সহকারী প্রধান শিক্ষক') || name.includes('তাপসী')) {
    return PHOTO_ASST_HEAD_TEACHER;
  }
  if (role === 'ict_teacher' || desig.includes('আইসিটি') || (teacher?.subject && teacher.subject.includes('আইসিটি')) || name.includes('আবুবকর')) {
    return PHOTO_ICT_TEACHER;
  }
  if (role === 'office_assistant' || desig.includes('অফিস') || desig.includes('হিসাব') || name.includes('আলমগীর') || empId.startsWith('stf')) {
    return PHOTO_OFFICE_ASSISTANT;
  }
  if (teacher?.gender === 'female' || teacher?.gender === 'নারী' || name.includes('খাতুন') || name.includes('বেগম') || name.includes('সুলতানা') || name.includes('আক্তার') || name.includes('রোকসানা') || name.includes('ফরিদা') || name.includes('সরকার')) {
    return PHOTO_FEMALE_TEACHER;
  }
  return PHOTO_MALE_TEACHER;
}

