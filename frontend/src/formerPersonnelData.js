const STORAGE_KEY = 'magra_db_former_personnel';

export function getStoredFormerPersonnelData() {
  if (typeof window === 'undefined' || !window.localStorage) {
    return DEFAULT_FORMER_PERSONNEL;
  }
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY);
    if (!raw) return DEFAULT_FORMER_PERSONNEL;
    const parsed = JSON.parse(raw);
    return {
      former_heads: Array.isArray(parsed.former_heads) ? parsed.former_heads : DEFAULT_FORMER_PERSONNEL.former_heads,
      former_assistants: Array.isArray(parsed.former_assistants) ? parsed.former_assistants : DEFAULT_FORMER_PERSONNEL.former_assistants,
      former_teachers: Array.isArray(parsed.former_teachers) ? parsed.former_teachers : DEFAULT_FORMER_PERSONNEL.former_teachers,
      former_staff: Array.isArray(parsed.former_staff) ? parsed.former_staff : DEFAULT_FORMER_PERSONNEL.former_staff
    };
  } catch (e) {
    console.error('Error reading former personnel from localStorage:', e);
    return DEFAULT_FORMER_PERSONNEL;
  }
}

export function saveStoredFormerPersonnelData(data) {
  if (typeof window === 'undefined' || !window.localStorage) return false;
  try {
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify(data));
    return true;
  } catch (e) {
    console.error('Error saving former personnel to localStorage:', e);
    return false;
  }
}
